-- Opiniões enviadas pelo formulário LuaHoje.
create table if not exists public.opinioes (
  id bigint generated by default as identity primary key,
  nome varchar(80) not null,
  opiniao varchar(1500) not null,
  criado_em timestamptz not null default now(),
  constraint opinioes_nome_valido check (length(btrim(nome)) between 2 and 80),
  constraint opinioes_texto_valido check (length(btrim(opiniao)) between 5 and 1500)
);

alter table public.opinioes enable row level security;

-- A aplicação pode inserir uma opinião, mas não pode ler a lista pública.
grant insert on table public.opinioes to anon, authenticated;
grant usage, select on sequence public.opinioes_id_seq to anon, authenticated;

drop policy if exists "Visitantes podem enviar opinioes" on public.opinioes;
create policy "Visitantes podem enviar opinioes"
  on public.opinioes
  for insert
  to anon, authenticated
  with check (
    length(btrim(nome)) between 2 and 80
    and length(btrim(opiniao)) between 5 and 1500
  );
